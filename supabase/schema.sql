-- ============================================================================
-- BingX VST migration (token optimization + exchange-neutral runtime)
-- ============================================================================

-- Venue attribution on existing records. Historical rows predate the migration
-- and are backfilled as 'okx'; every new VST record is written as 'bingx'.
alter table public.trades add column if not exists exchange text;
update public.trades set exchange = 'okx' where exchange is null;
alter table public.trades alter column exchange set default 'bingx';
alter table public.trades alter column exchange set not null;
create index if not exists trades_exchange_closed_at_idx on public.trades (exchange, closed_at desc);

alter table public.ai_decisions add column if not exists exchange text;
update public.ai_decisions set exchange = 'okx' where exchange is null;
alter table public.ai_decisions alter column exchange set default 'bingx';
alter table public.ai_decisions alter column exchange set not null;
alter table public.ai_decisions add column if not exists ai_call_id text;
create index if not exists ai_decisions_ai_call_id_idx on public.ai_decisions (ai_call_id);
create index if not exists ai_decisions_exchange_created_at_idx on public.ai_decisions (exchange, created_at desc);

