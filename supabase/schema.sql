create table if not exists public.trades (
    id bigint generated by default as identity primary key,
    created_at timestamptz not null default now(),
    symbol text not null,
    direction text not null check (direction in ('LONG', 'SHORT')),
    entry_price double precision not null,
    exit_price double precision not null,
    quantity double precision not null,
    pnl_usdt double precision not null,
    reason text not null,
    entry_reason text not null,
    opened_at timestamptz not null,
    closed_at timestamptz not null,
    exchange_entry_order_id text not null,
    exchange_exit_order_id text not null
);

create index if not exists trades_closed_at_idx on public.trades (closed_at desc);
create index if not exists trades_symbol_closed_at_idx on public.trades (symbol, closed_at desc);

create table if not exists public.ai_decisions (
    id bigint generated by default as identity primary key,
    created_at timestamptz not null default now(),
    symbol text not null,
    action text not null,
    confidence double precision not null,
    systemic_risk integer not null check (systemic_risk between 1 and 5),
    reason text not null,
    payload_json jsonb not null
);

create index if not exists ai_decisions_created_at_idx on public.ai_decisions (created_at desc);
create index if not exists ai_decisions_symbol_created_at_idx on public.ai_decisions (symbol, created_at desc);

alter table public.trades enable row level security;
alter table public.ai_decisions enable row level security;
