create table if not exists public.trades (
    id bigint generated by default as identity primary key,
    created_at timestamptz not null default now(),
    symbol text not null,
    direction text not null check (direction in ('LONG', 'SHORT')),
    entry_price double precision not null,
    exit_price double precision not null,
    quantity double precision not null,
    pnl_usdt double precision not null,
    reason text not null,
    entry_reason text not null,
    opened_at timestamptz not null,
    closed_at timestamptz not null,
    exchange_entry_order_id text not null,
    exchange_exit_order_id text not null,
    confidence double precision not null default 0,
    factor_metadata jsonb not null default '{}'::jsonb,
    trigger_metadata jsonb not null default '{}'::jsonb
);

alter table public.trades add column if not exists confidence double precision not null default 0;
alter table public.trades add column if not exists factor_metadata jsonb not null default '{}'::jsonb;
alter table public.trades add column if not exists trigger_metadata jsonb not null default '{}'::jsonb;

create index if not exists trades_closed_at_idx on public.trades (closed_at desc);
create index if not exists trades_symbol_closed_at_idx on public.trades (symbol, closed_at desc);
create index if not exists trades_factor_metadata_gin_idx on public.trades using gin (factor_metadata);
create index if not exists trades_trigger_metadata_gin_idx on public.trades using gin (trigger_metadata);

