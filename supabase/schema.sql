-- Persistent open-position lifecycle state so a restart can resume a known
-- BingX position instead of treating it as unknown exposure.
create table if not exists public.open_position_state (
    id bigint generated by default as identity primary key,
    exchange text not null default 'bingx',
    symbol text not null,
    status text not null default 'open' check (status in ('opening', 'open', 'closing', 'closed')),
    position_id text,
    direction text not null check (direction in ('LONG', 'SHORT')),
    quantity double precision not null default 0,
    exchange_size double precision not null default 0,
    entry_price double precision not null default 0,
    stop_loss_pct double precision,
    take_profit_pct double precision,
    exchange_order_id text,
    exit_order_id text,
    client_order_id text,
    fill_details jsonb not null default '{}'::jsonb,
    entry_reason text,
    opened_at timestamptz,
    updated_at timestamptz not null default now(),
    unique (exchange, symbol)
);

create index if not exists open_position_state_status_idx on public.open_position_state (exchange, status);

alter table public.open_position_state enable row level security;
